// scripts/sound/bundle.mjs
// Bundle the engine modules into one browser-loadable JS file. The output
// is a self-contained classic script (no <script type="module">) that
// HyperFrames can serve and that any composition can load via
// <script src="./sound.js"></script>.
//
// Why a custom bundler and not esbuild/rollup? Two reasons:
//   1. Zero new dependencies. The repo is a pure Node setup, and adding
//      a bundler is more risk than reward for 6 small modules.
//   2. The output is fully visible / auditable — no minification, no
//      magic. A future maintainer can read sound.js top-to-bottom and
//      understand what the sound system does.
//
// What the bundle does:
//   1. Reads registry.mjs, resolver.mjs, controller.mjs, session.mjs,
//      profile-paper-explainer.mjs, bundle.template.mjs in dependency order.
//   2. Strips the `export` keyword from each (since the output is a
//      classic script with a shared IIFE scope) and rewrites imports
//      to reference the inlined locals.
//   3. Prepends a tiny shim that defines the imports the bundle expects.
//   4. Writes the result to <out>.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ENGINE = __dirname;
const TEMPLATE = join(ENGINE, "bundle.template.mjs");
const out = process.argv[2];
if (!out) {
  console.error("usage: node scripts/sound/bundle.mjs <output.js>");
  process.exit(1);
}

const FILES = [
  "registry.mjs",
  "controller.mjs",
  "resolver.mjs",
  "session.mjs",
  "profile-paper-explainer.mjs",
];

const blocks = {};
for (const f of FILES) {
  const src = await readFile(join(ENGINE, f), "utf8");
  blocks[f] = stripExports(src);
}

const template = await readFile(TEMPLATE, "utf8");

// The template imports from "./sound-engine.mjs" — replace that with a
// shared inlined scope. The trick: we wrap the whole bundle in one IIFE
// and the template's import statement is rewritten to a destructure of
// the IIFE's locals.
const sharedScope = `
const {
  REGISTRY, SFX_BASE_DIR, getEffect, pickAsset, pickPlaybackRate,
  resolve, resolveAll,
  SoundController, SoundSession,
  paperExplainerProfile,
} = (function () {
${Object.entries(blocks).map(([f, src]) => `// ── ${f} ──\n${src}`).join("\n\n")}
  return {
    REGISTRY, SFX_BASE_DIR, getEffect, pickAsset, pickPlaybackRate,
    resolve, resolveAll,
    SoundController, SoundSession,
    paperExplainerProfile,
  };
})();
`;

const templateBody = template
  .replace(/^import .* from .*$/m, "")             // remove the import line
  .replace(/from "\.\/sound-engine\.mjs"/, "");   // (in case the import spans lines)

const out_src =
  "// Auto-generated by scripts/sound/bundle.mjs. Do not edit by hand.\n" +
  "// Source: scripts/sound/{registry,resolver,controller,session,profile-paper-explainer,bundle.template}.mjs\n" +
  sharedScope +
  "\n" +
  templateBody +
  "\n";

await writeFile(resolve(out), out_src, "utf8");
console.log(`wrote ${out} (${out_src.length} bytes)`);

// ─── helpers ─────────────────────────────────────────────────────────

function stripExports(src) {
  // Convert ESM syntax into plain declarations so the bundle can run as
  // a classic script inside one shared IIFE scope.
  return src
    .replace(/^export\s+const\s+/gm, "const ")
    .replace(/^export\s+function\s+/gm, "function ")
    .replace(/^export\s+class\s+/gm, "class ")
    .replace(/^export\s*\{[^}]*\};?\s*$/gm, "")
    // Multi-line `import { a, b, c } from "./x.mjs";` — strip whole.
    .replace(/^import\s*[\s\S]*?from\s*["'][^"']+["'];?\s*$/gm, "")
    // Single-line `import X from "...";`
    .replace(/^import\s+[^;]+;?\s*$/gm, "");
}
